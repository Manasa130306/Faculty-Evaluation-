export function getMonthFramework(month: string): MonthFramework {
  const norm = month.charAt(0).toUpperCase() + month.slice(1).toLowerCase();
  return (
    APPRAISAL_FRAMEWORK[norm] || {
      month: norm,
      order: 1,
      totalMarks: 0,
      heads: {},
    }
  );
}

export function getHeadMetric(month: string, headNumber: number): HeadMetric {
  const fw = getMonthFramework(month);
  if (fw.heads[headNumber]) {
    return fw.heads[headNumber];
  }
  const genericHead = PERFORMANCE_HEADS.find((h) => h.number === headNumber);
  return {
    headNumber,
    name: genericHead ? genericHead.name : `Head ${headNumber}`,
    maxMarks: 0,
    description: 'No weightage allocated this month.',
    isAdminOnly: headNumber === 1,
    requiresDocument: false,
  };
}
